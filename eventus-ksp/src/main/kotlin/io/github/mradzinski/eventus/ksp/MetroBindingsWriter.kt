package io.github.mradzinski.eventus.ksp

import com.google.devtools.ksp.getConstructors
import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.symbol.ClassKind
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.Modifier

/**
 * Writes the Metro binding container of one screen: an object contributed to the screen's scope that
 * provides each of its handlers into a set of the screen's handler interface.
 */
internal fun writeMetroBindings(bindings: MetroBindings, codeGenerator: CodeGenerator) {
    val screen = bindings.screen

    val sources = (bindings.handlers.map { it.declaration } + screen).mapNotNull { it.containingFile }

    // Aggregating: a handler added or deleted anywhere in the module changes this file.
    val file = codeGenerator.createNewFile(
        dependencies = Dependencies(aggregating = true, sources = sources.distinct().toTypedArray()),
        packageName = screen.packageName.asString(),
        fileName = screen.containerName(),
    )

    file.use { it.write(bindings.source().toByteArray()) }
}

private fun MetroBindings.source(): String {
    // As visible as the interface: a graph in another Gradle module sees only a public container.
    val visibility = if (Modifier.INTERNAL in screen.modifiers) "internal" else "public"

    val stars = screen.typeParameters.joinToString { "*" }
    val element = if (stars.isEmpty()) screen.displayName else "${screen.displayName}<$stars>"
    val simpleNames = handlers.map { it.declaration.simpleName.asString() }

    val providers = handlers.joinToString(separator = "\n\n") { handler ->
        val isOnlyOneOfItsName = simpleNames.count { it == handler.declaration.simpleName.asString() } == 1

        handler.declaration.provider(
            name = handler.declaration.providerName(simple = isOnlyOneOfItsName),
            visibility = visibility,
            element = element,
        )
    }

    return """
        |// Generated by eventus-ksp. Do not edit: it is written again on every build.
        |package ${screen.packageName.asString()}
        |
        |import dev.zacsweers.metro.BindingContainer
        |import dev.zacsweers.metro.ContributesTo
        |import dev.zacsweers.metro.IntoSet
        |import dev.zacsweers.metro.Origin
        |import dev.zacsweers.metro.Provides
        |
        |@ContributesTo($scope::class)
        |@BindingContainer
        |@Origin(${screen.displayName}::class)
        |$visibility object ${screen.containerName()} {
        |
        |$providers
        |}
        |
    """.trimMargin()
}

/** `EventusTaskListHandlerBindings` for `TaskListHandler`; a nested interface keeps the names around it. */
private fun KSClassDeclaration.containerName(): String {
    val nameInPackage = displayName
        .removePrefix(packageName.asString())
        .replace(oldValue = ".", newValue = "")

    return "Eventus${nameInPackage}Bindings"
}

/** The handler's own name, or its full name where one screen has two handlers of that name. */
private fun KSClassDeclaration.providerName(simple: Boolean): String {
    val name = if (simple) simpleName.asString() else displayName.replace(oldValue = ".", newValue = "_")

    return name.replaceFirstChar { it.lowercaseChar() }
}

/**
 * One provider: Metro supplies the parameters, which are those of the handler's constructor, and the
 * handler joins the set of [element]. The handler class is named only in the body, so it can be internal.
 */
private fun KSClassDeclaration.provider(
    name: String,
    visibility: String,
    element: String,
): String {
    val signature = "    @Provides\n    @IntoSet\n    $visibility fun $name"

    if (classKind == ClassKind.OBJECT) return "$signature(): $element = $displayName"

    // A class with no primary constructor has at least one written out, or it would have the default one.
    val constructor = primaryConstructor ?: getConstructors().first()

    val parameters = constructor.parameters.mapIndexed { index, parameter ->
        "        ${parameter.qualifiers()}p$index: ${parameter.type.resolve().toSource()},\n"
    }

    val arguments = List(parameters.size) { "p$it" }.joinToString()

    if (parameters.isEmpty()) return "$signature(): $element = $displayName()"

    return "$signature(\n${parameters.joinToString(separator = "")}    ): $element = $displayName($arguments)"
}
