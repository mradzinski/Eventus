package io.github.mradzinski.eventus.ksp

import com.google.devtools.ksp.getConstructors
import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.symbol.ClassKind
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.KSPropertyDeclaration
import com.google.devtools.ksp.symbol.Modifier

/** Writes the `actual` of [property]: a Koin module with every handler and error handler of the [scan]. */
internal fun writeKoinModule(
    property: KSPropertyDeclaration,
    scan: Scan,
    codeGenerator: CodeGenerator,
) {
    val handlers = scan.handlers
        .filter { it.isRoutable() }
        .sortedBy { it.declaration.displayName }

    val errorHandlers = scan.errorHandlers.sortedBy { it.displayName }

    val sources = (handlers.map { it.declaration } + errorHandlers + property).mapNotNull { it.containingFile }

    // Sorted, so every target generates the same file. Aggregating: a handler added or deleted anywhere in
    // the module changes this file.
    val lines = handlers.map { it.definition() } + errorHandlers.map { it.creation() }

    val name = property.simpleName.asString()

    val file = codeGenerator.createNewFile(
        dependencies = Dependencies(aggregating = true, sources = sources.distinct().toTypedArray()),
        packageName = property.packageName.asString(),
        fileName = "Eventus" + name.first().uppercaseChar() + name.drop(1),
    )

    file.use { it.write(property.source(lines).toByteArray()) }
}

private fun KSPropertyDeclaration.source(definitions: List<String>): String {
    val visibility = if (Modifier.INTERNAL in modifiers) "internal" else "public"
    val body = definitions.joinToString(separator = "\n") { "    $it" }

    return """
        |// Generated by eventus-ksp. Do not edit: it is written again on every build.
        |package ${packageName.asString()}
        |
        |import org.koin.core.module.Module
        |import org.koin.core.qualifier.named
        |import org.koin.dsl.bind
        |import org.koin.dsl.module
        |
        |@$KOIN_MODULE_ANNOTATION
        |$visibility actual val ${simpleName.asString()}: Module = module {
        |$body
        |}
        |
    """.trimMargin()
}

/**
 * One line of the module: the handler as a factory, bound to the handler interface of its screen.
 *
 * The factory is named after the handler's full name. On JS and Wasm Koin knows a class by its simple name
 * only, so without a name of its own a handler would silently replace the handler of the same simple name
 * of another screen, and that screen would be left without it.
 */
private fun Handler.definition(): String {
    val bindings = screenInterfaces.joinToString(separator = "") { " bind ${it.displayName}::class" }

    val name = "named(\"${declaration.displayName}\")"

    return declaration.creation(qualifier = name) + bindings
}

/**
 * Written out in full, not as `factoryOf(::Handler)`: a constructor reference takes a simple name, and two
 * screens often have a handler of the same name.
 */
private fun KSClassDeclaration.creation(qualifier: String? = null): String {
    val factory = if (qualifier == null) "factory" else "factory($qualifier)"

    if (classKind == ClassKind.OBJECT) return "$factory { $displayName }"

    // A class with no primary constructor has at least one written out, or it would have the default one.
    val constructor = primaryConstructor ?: getConstructors().first()

    val arguments = List(constructor.parameters.size) { "get()" }.joinToString()

    return "$factory { $displayName($arguments) }"
}
