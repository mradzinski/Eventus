// Named differently from the :eventus module, so the generated project accessors do not clash.
rootProject.name = "eventus-root"

pluginManagement {
    repositories {
        google()
        mavenCentral()
        gradlePluginPortal()
    }
}

dependencyResolutionManagement {
    repositories {
        google()
        mavenCentral()
    }
}

enableFeaturePreview("TYPESAFE_PROJECT_ACCESSORS")

// The project's own ktlint rules, added to every module's ktlintRuleset by the root build script.
includeBuild("tooling/ktlint-rules")

// The library.
include(":eventus")

// Optional additions to the library, each published as its own artifact: the annotation that asks for a
// generated Koin module, the annotation that asks for generated Metro bindings, and the symbol processor that
// checks every event has a handler and writes both.
include(":eventus-koin")
include(":eventus-metro")
include(":eventus-ksp")
// Optional helpers for a Compose UI: collecting effects, and telling the router the screen is visible.
include(":eventus-compose")
// Optional helper for an app's tests: runs event handlers through a router inside a coroutine test.
include(":eventus-test")

// The sample app, wired with Koin: the domain, the data layer, what the screens share, one api and one impl
// module per feature, the app that puts them together, and one entry-point module per platform.
// The iOS entry point is the Xcode project in sample-koin/iosApp, which is not a Gradle module.
include(":sample-koin:core:domain")
include(":sample-koin:core:data")
include(":sample-koin:core:ui")
include(":sample-koin:core:testing")
include(":sample-koin:feature:tasklist:api")
include(":sample-koin:feature:tasklist:impl")
include(":sample-koin:feature:taskeditor:api")
include(":sample-koin:feature:taskeditor:impl")
include(":sample-koin:app")
include(":sample-koin:androidApp")
include(":sample-koin:desktopApp")
include(":sample-koin:webApp")

// Not published: a small multiplatform module that runs the Metro bindings generated by eventus-ksp through
// the real Metro compiler plugin, which the sample (wired with Koin) does not.
// The same sample app, wired with Metro. Its modules mirror those of sample-koin.
include(":sample-metro:core:domain")
include(":sample-metro:core:data")
include(":sample-metro:core:ui")
include(":sample-metro:core:testing")
include(":sample-metro:feature:tasklist:api")
include(":sample-metro:feature:tasklist:impl")
include(":sample-metro:feature:taskeditor:api")
include(":sample-metro:feature:taskeditor:impl")
include(":sample-metro:app")
include(":sample-metro:androidApp")
include(":sample-metro:desktopApp")
include(":sample-metro:webApp")
